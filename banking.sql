create database bankingsystems;
use bankingsystems;
CREATE TABLE Customers (
    CustomerID INT AUTO_INCREMENT PRIMARY KEY,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    Email VARCHAR(100) UNIQUE,
    Phone VARCHAR(20),
    Address VARCHAR(255),
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE ACCOUNTS(
    ACCOUNTID INT AUTO_INCREMENT PRIMARY KEY,
    ACCOUNTTYPE VARCHAR(60) NOT NULL,
    BALANCE DECIMAL(15,2) DEFAULT 0.00,
    STATUS VARCHAR(30) DEFAULT 'ACTIVE',
    CREATEDAT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerTD)
);
CREATE TABLE TRANSACTION(
    TRANSACTIONID INT AUTO_INCREMENT PRIMARY KEY,
    ACCOUNTID INT,
    TRANSACTIONTYPE VARCHAR(60) NOT NULL,
    AMOUNT DECIMAL(15,2) NOT NULL,
    TRANSACTIONDARE DATETIME DEFAULT CURRENT_TIMESTAMP,
    DESCRIPTION VARCHAR(455),
    FOREIGN KEY (ACCOUNTID) REFERENCES ACCOUNTS(ACCOUNTID)
);
